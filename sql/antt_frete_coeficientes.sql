-- Tabela de coeficientes do piso mínimo de frete (ANTT - PNPM-TRC).
-- Piso = (CCD × distância_km) + CC, por tipo de carga, nº de eixos e tipo de contratação.
--   COMPOSICAO = Tabela A (cavalo + carreta)  ·  TRACAO = Tabela B (só o veículo)
--
-- Seed: Resolução ANTT 5.867/2020 (Anexo II, Tabelas A e B). ATENÇÃO: esses
-- coeficientes estão DEFASADOS — a ANTT reajusta periodicamente (ex.: Res. 6.076/2026).
-- A estrutura é versionada por `vigencia`: ao importar uma tabela mais nova,
-- o sistema passa a usar a vigência mais recente automaticamente.
--
-- Aplicar:
--   mysql -h 127.0.0.1 -P 3307 -u root sistema_frotas < sql/antt_frete_coeficientes.sql

CREATE TABLE IF NOT EXISTS antt_frete_coeficientes (
    id INT AUTO_INCREMENT PRIMARY KEY,
    vigencia DATE NOT NULL,
    tipo_carga VARCHAR(40) NOT NULL,
    eixos TINYINT UNSIGNED NOT NULL,
    ccd DECIMAL(12,4) NOT NULL,
    cc DECIMAL(12,2) NOT NULL,
    contratacao ENUM('COMPOSICAO','TRACAO') NOT NULL DEFAULT 'COMPOSICAO',
    alto_desempenho CHAR(1) NOT NULL DEFAULT 'N',
    ativo CHAR(1) NOT NULL DEFAULT 'S',
    UNIQUE KEY uniq_coef (vigencia, tipo_carga, eixos, contratacao, alto_desempenho)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

